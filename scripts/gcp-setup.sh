#!/usr/bin/env bash
# One-time Google Cloud / Firebase setup for the SaaS backend (PHASE1-PLAN.md, "Your setup steps").
#
#   bash scripts/gcp-setup.sh <project-id> [billing-account-id]
#
# Safe to re-run: every step skips what already exists. Uses --project on every command and
# never changes your gcloud default project. The Anthropic key is read with a hidden prompt
# and piped straight into Secret Manager — it's never printed, logged, or written to disk.
set -euo pipefail

PROJECT="${1:-}"
BILLING="${2:-}"
REGION="europe-west1"
FIRESTORE_LOCATION="eur3"
SITE_DOMAIN="recipe-transcriber.pages.dev"
BUDGET_AMOUNT="20" # in the billing account's currency
WEB_ENV_FILE="$(cd "$(dirname "$0")/.." && pwd)/web/.env.cloud.local"

if [[ -z "$PROJECT" ]]; then
  echo "Usage: bash scripts/gcp-setup.sh <project-id> [billing-account-id]"
  echo "  project-id: globally unique, 6-30 chars, lowercase/digits/hyphens (e.g. recipe-transcriber-eu)"
  exit 1
fi

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m  ! %s\033[0m\n' "$*"; }
ok() { printf '\033[32m  ✓ %s\033[0m\n' "$*"; }
TODO=()

token() { gcloud auth print-access-token; }
# REST call to a Google API, billed/quota'd against the new project.
api() { # api METHOD URL [JSON]
  curl -sS -X "$1" "$2" \
    -H "Authorization: Bearer $(token)" \
    -H "x-goog-user-project: $PROJECT" \
    -H "Content-Type: application/json" \
    ${3:+-d "$3"}
}
# Poll a long-running operation (Firebase management API) until done.
wait_op() { # wait_op OPERATION_NAME
  for _ in $(seq 1 30); do
    local res
    res="$(api GET "https://firebase.googleapis.com/v1beta1/$1")"
    if grep -q '"done": true' <<<"$res"; then echo "$res"; return 0; fi
    sleep 2
  done
  return 1
}

step "Account"
gcloud auth list --filter=status:ACTIVE --format="value(account)" | sed 's/^/  signed in as /'

step "1. Project $PROJECT"
if gcloud projects describe "$PROJECT" >/dev/null 2>&1; then
  ok "already exists"
else
  gcloud projects create "$PROJECT" --name="Recipe Transcriber"
fi

step "1b. Billing"
if [[ -z "$BILLING" ]]; then
  # (no mapfile: macOS ships bash 3.2)
  ACCOUNTS="$(gcloud billing accounts list --filter=open=true --format="value(name.basename())")"
  if [[ -n "$ACCOUNTS" && $(wc -l <<<"$ACCOUNTS") -eq 1 ]]; then
    BILLING="$ACCOUNTS"
  else
    gcloud billing accounts list --filter=open=true
    read -rp "  Billing account ID to use: " BILLING
  fi
fi
gcloud billing projects link "$PROJECT" --billing-account="$BILLING" >/dev/null
ok "linked to $BILLING"

step "2. Enable APIs (takes a minute)"
gcloud services enable --project="$PROJECT" \
  firebase.googleapis.com firestore.googleapis.com firebaserules.googleapis.com \
  identitytoolkit.googleapis.com firebaseappcheck.googleapis.com recaptchaenterprise.googleapis.com \
  run.googleapis.com cloudbuild.googleapis.com artifactregistry.googleapis.com \
  secretmanager.googleapis.com billingbudgets.googleapis.com
ok "enabled"

step "2b. Add Firebase to the project"
if api GET "https://firebase.googleapis.com/v1beta1/projects/$PROJECT" | grep -q '"projectId"'; then
  ok "already a Firebase project"
else
  RES="$(api POST "https://firebase.googleapis.com/v1beta1/projects/$PROJECT:addFirebase" '{}')"
  if OP="$(grep -o '"name": *"operations/[^"]*"' <<<"$RES" | sed 's/.*"operations/operations/;s/"$//')" && [[ -n "$OP" ]]; then
    wait_op "$OP" >/dev/null && ok "added"
  else
    warn "couldn't add Firebase via the API: $(tr -d '\n' <<<"$RES" | head -c 300)"
    TODO+=("Firebase console → Add project → pick '$PROJECT' (accept the Firebase terms), then re-run this script")
  fi
fi

step "2c. Register the web app"
APP_ID="$(api GET "https://firebase.googleapis.com/v1beta1/projects/$PROJECT/webApps" \
  | grep -o '"appId": *"[^"]*"' | head -1 | sed 's/.*: *"//;s/"$//' || true)"
if [[ -z "$APP_ID" ]]; then
  RES="$(api POST "https://firebase.googleapis.com/v1beta1/projects/$PROJECT/webApps" '{"displayName":"Recipe Transcriber web"}')"
  OP="$(grep -o '"name": *"operations/[^"]*"' <<<"$RES" | sed 's/.*"operations/operations/;s/"$//' || true)"
  if [[ -n "$OP" ]] && DONE="$(wait_op "$OP")"; then
    APP_ID="$(grep -o '"appId": *"[^"]*"' <<<"$DONE" | head -1 | sed 's/.*: *"//;s/"$//')"
  fi
fi
if [[ -n "$APP_ID" ]]; then
  ok "web app $APP_ID"
  # The Firebase web config is public by design (it ships in the site), but keep it out of
  # git anyway: web/.env.cloud.local is covered by .gitignore (.env.*).
  CONFIG="$(api GET "https://firebase.googleapis.com/v1beta1/projects/$PROJECT/webApps/$APP_ID/config")"
  field() { grep -o "\"$1\": *\"[^\"]*\"" <<<"$CONFIG" | sed 's/.*: *"//;s/"$//'; }
  {
    echo "# Generated by scripts/gcp-setup.sh — Firebase web config (public, not a secret)"
    echo "VITE_FIREBASE_API_KEY=$(field apiKey)"
    echo "VITE_FIREBASE_AUTH_DOMAIN=$(field authDomain)"
    echo "VITE_FIREBASE_PROJECT_ID=$(field projectId)"
    echo "VITE_FIREBASE_APP_ID=$(field appId)"
    echo "VITE_FIREBASE_MESSAGING_SENDER_ID=$(field messagingSenderId)"
  } >"$WEB_ENV_FILE"
  ok "wrote web config to web/.env.cloud.local"
else
  warn "couldn't register the web app"
  TODO+=("Firebase console → Project settings → Add app → Web")
fi

step "4. Firestore in $FIRESTORE_LOCATION (permanent)"
if gcloud firestore databases describe --database="(default)" --project="$PROJECT" >/dev/null 2>&1; then
  ok "already exists ($(gcloud firestore databases describe --database='(default)' --project="$PROJECT" --format='value(locationId)'))"
else
  gcloud firestore databases create --database="(default)" --location="$FIRESTORE_LOCATION" \
    --type=firestore-native --project="$PROJECT"
fi

step "3. Authentication: email link + authorized domain"
AUTH_BODY="$(cat <<JSON
{"signIn":{"email":{"enabled":true,"passwordRequired":false}},
 "authorizedDomains":["localhost","$PROJECT.firebaseapp.com","$PROJECT.web.app","$SITE_DOMAIN"]}
JSON
)"
RES="$(api PATCH "https://identitytoolkit.googleapis.com/admin/v2/projects/$PROJECT/config?updateMask=signIn.email.enabled,signIn.email.passwordRequired,authorizedDomains" "$AUTH_BODY")"
if grep -q '"error"' <<<"$RES"; then
  warn "couldn't configure Auth via the API ($(grep -o '"message": *"[^"]*"' <<<"$RES" | head -1))"
  TODO+=("Firebase console → Authentication → Get started → Email/Password → enable 'Email link (passwordless sign-in)'")
  TODO+=("Firebase console → Authentication → Settings → Authorized domains → add $SITE_DOMAIN")
else
  ok "email link on; authorized: localhost, $SITE_DOMAIN"
fi
# Google sign-in needs an OAuth client + consent screen, which only the console sets up cleanly.
TODO+=("Firebase console → Authentication → Sign-in method → Add new provider → Google → Enable (pick your support email)")

step "5. App Check with reCAPTCHA Enterprise"
SITE_KEY="$(gcloud recaptcha keys list --project="$PROJECT" --filter='displayName="recipe-transcriber-web"' \
  --format='value(name.basename())' 2>/dev/null | head -1 || true)"
if [[ -z "$SITE_KEY" ]]; then
  SITE_KEY="$(gcloud recaptcha keys create --project="$PROJECT" --display-name="recipe-transcriber-web" \
    --web --integration-type=score --domains="$SITE_DOMAIN,localhost" \
    --format='value(name.basename())' 2>/dev/null || true)"
fi
if [[ -n "$SITE_KEY" && -n "$APP_ID" ]]; then
  RES="$(api PATCH "https://firebaseappcheck.googleapis.com/v1/projects/$PROJECT/apps/$APP_ID/recaptchaEnterpriseConfig?updateMask=siteKey" "{\"siteKey\":\"$SITE_KEY\"}")"
  if grep -q '"error"' <<<"$RES"; then
    warn "site key created but App Check registration failed"
    TODO+=("Firebase console → App Check → Apps → register the web app with reCAPTCHA Enterprise, site key $SITE_KEY")
  else
    ok "web app registered (site key $SITE_KEY)"
  fi
  grep -q '^VITE_APPCHECK_SITE_KEY=' "$WEB_ENV_FILE" 2>/dev/null || echo "VITE_APPCHECK_SITE_KEY=$SITE_KEY" >>"$WEB_ENV_FILE"
else
  warn "couldn't set up App Check"
  TODO+=("Firebase console → App Check → register the web app with reCAPTCHA Enterprise")
fi

step "6. Budget alert ($BUDGET_AMOUNT/month at 50/90/100%)"
if gcloud billing budgets list --billing-account="$BILLING" --billing-project="$PROJECT" --quiet --format='value(displayName)' 2>/dev/null \
  | grep -qx "Recipe Transcriber ($PROJECT)"; then
  ok "already exists"
elif gcloud billing budgets create --billing-account="$BILLING" --billing-project="$PROJECT" --quiet \
  --display-name="Recipe Transcriber ($PROJECT)" --budget-amount="$BUDGET_AMOUNT" \
  --filter-projects="projects/$PROJECT" \
  --threshold-rule=percent=0.5 --threshold-rule=percent=0.9 --threshold-rule=percent=1.0 >/dev/null; then
  ok "created"
else
  warn "couldn't create the budget (needs Billing Account Administrator)"
  TODO+=("Cloud console → Billing → Budgets & alerts → create a $BUDGET_AMOUNT/month budget for $PROJECT")
fi

step "8. Secret Manager: anthropic-api-key"
if gcloud secrets describe anthropic-api-key --project="$PROJECT" >/dev/null 2>&1; then
  ok "already exists (add a new version with: gcloud secrets versions add anthropic-api-key --data-file=- --project=$PROJECT)"
else
  read -rsp "  Paste your Anthropic API key (input hidden, Enter to skip): " ANTHROPIC_KEY; echo
  if [[ -n "$ANTHROPIC_KEY" ]]; then
    printf '%s' "$ANTHROPIC_KEY" | gcloud secrets create anthropic-api-key --project="$PROJECT" \
      --replication-policy=user-managed --locations="$REGION" --data-file=- >/dev/null
    ok "stored (not printed)"
  else
    TODO+=("Store the key: gcloud secrets create anthropic-api-key --project=$PROJECT --replication-policy=user-managed --locations=$REGION --data-file=-   (paste, then Ctrl-D)")
  fi
  unset ANTHROPIC_KEY
fi

step "Done"
echo "  Project: $PROJECT   Region: $REGION   Firestore: $FIRESTORE_LOCATION"
if [[ ${#TODO[@]} -gt 0 ]]; then
  echo
  echo "  Still to do by hand (https://console.firebase.google.com/project/$PROJECT):"
  for t in "${TODO[@]}"; do echo "   - $t"; done
fi
